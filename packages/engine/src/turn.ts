import { opponentOf } from './player.js'
import type { Player } from './player.js'

/**
 * ターンを構成するフェイズ。
 *
 * ターンはこの 6 つの連続するフェイズで構成され、それぞれのフェイズは何も起こらない
 * 場合でも存在する（総合ルール 第3部 第4章 2）。並びは総合ルールの順のままで、
 * フェイズはこの順に進む。
 */
export const PHASES = [
  'リリースフェイズ',
  'ドローフェイズ',
  'エネルギーフェイズ',
  'メインフェイズ',
  'スマッシュフェイズ',
  'リカバリーフェイズ',
] as const

export type Phase = (typeof PHASES)[number]

/**
 * 進行中のターンと、その中でどこまで進んでいるか。
 *
 * 優先権をターンに持たせているのは、優先権がフェイズの始めに発生し、両方のプレイヤーが
 * 連続して放棄した時にそのフェイズが終わる（総合ルール 第3部 第4章 4）という形で、
 * 優先権の行き来がフェイズの進み方そのものになっているためである。
 */
export interface Turn {
  /**
   * 通算のターン数。デュエルの最初のターン、すなわち先攻のプレイヤーのターン
   * （総合ルール 第3部 第4章 1）を 1 として数える。
   *
   * 数え方そのものは総合ルールの語ではないが、「先攻の第 1 ターン」（同 第2章 2）を
   * 指すのに要る。
   */
  readonly number: number
  /** 進行中のターンを持つプレイヤー。 */
  readonly active: Player
  readonly phase: Phase
  /** いま優先権を持っているプレイヤー。 */
  readonly priority: Player
  /**
   * 直前に優先権を放棄したプレイヤー。このフェイズでまだ誰も放棄していなければ
   * `undefined`。
   *
   * フェイズが終わるのは両方のプレイヤーが「連続して」放棄した時（総合ルール 第3部
   * 第4章 4）なので、放棄が続いているかどうかを覚えておく必要がある。誰が優先権を
   * 持っているかからは決まらない。行動が行われれば連続は途切れる。
   */
  readonly passedBy: Player | undefined
  /**
   * リカバリーフェイズで、「ターンの終わり」に誘発する能力をすでに誘発させたか
   * （総合ルール 第3部 第10章 3）。
   *
   * リカバリーフェイズは、連続放棄を 2 度必要とする唯一のフェイズである。1 度目で
   * 「ターンの終わり」の能力が誘発し、2 度目でフェイズが終わる（同 3・4）。その 1 度目が
   * 済んでいるかどうかをここで覚えておく。他のフェイズでは常に `false` のまま。
   */
  readonly endOfTurnTriggered: boolean
}

/**
 * そのフェイズが始まった状態のターン。
 *
 * フェイズの始めには非アクティブプレイヤーに優先権が発生する（総合ルール 第3部
 * 第5章 1・第6章 1-1・第7章 1・第8章 1・第9章 1・第10章 1）。どのフェイズも同じなので
 * ここにまとめている。
 */
export function beginPhase(number: number, active: Player, phase: Phase): Turn {
  return {
    number,
    active,
    phase,
    priority: opponentOf(active),
    passedBy: undefined,
    endOfTurnTriggered: false,
  }
}

/**
 * デュエルの最初のターン。先攻のプレイヤーのターンから始まる（総合ルール 第3部 第4章 1）。
 *
 * リリースフェイズが始まったところから始める。このフェイズの始めの処理（同 第5章 1）を
 * 通していないのは、デュエルの開始時にはそれが必ず空振りになるためである。スクエア・
 * トラップゾーン・エネルギーゾーン・スマッシュゾーンはいずれも空でリリースするカードが
 * 無く、盤面にカードが無い以上「ターンの始め」に誘発する能力も存在しない（総合ルール
 * 第2部 第21章 3-1・5-1・6-1・7-1・8-1・9-1）。第 1 ターンのドローフェイズも
 * とばされる（同 第3部 第2章 2）。
 */
export function firstTurn(): Turn {
  return beginPhase(1, '先攻', PHASES[0])
}
