import { damagePlayer } from './effect.js'
import type { Effect } from './effect.js'
import { PHASES } from './turn.js'
import type { Phase } from './turn.js'

/**
 * そのフェイズが始まったこと。
 *
 * どのフェイズにも「～フェイズの始め」に誘発する能力があり得る（総合ルール 第3部
 * 第5章 1・第6章 1-1・第7章 1・第8章 1・第9章 1・第10章 1）ため、フェイズの並びから
 * 作る。フェイズを足したのに誘発イベントを足し忘れる、ということが起こらないようにする。
 */
export function phaseBeginning(phase: Phase): `${Phase}の始め` {
  return `${phase}の始め`
}

/**
 * 誘発型能力を誘発させるできごと。
 *
 * テキストの「～の始めに」「～の終わりに」「～した時」にあたる語句
 * （総合ルール 第4部 第3章 1）。
 *
 * 並びは、ターンの進行に伴って起こるもの、ユニットの登場・移動、バトルの中で起こるもの、
 * ターンの中の一点に置けないもの、の順。はじめの 3 つは、ターンの中で起こる順に並ぶ。
 * スマッシュ判定のできごと、リリースした時（同 第3部 第5章 1）・カードを引いた時
 * （同 第6章 1-1）といった、そこで起きる行動に伴うできごとは、その行動を実装する時に足す。
 */
export const TRIGGER_EVENTS = [
  // 総合ルール 第3部 第5章 1。ターンの始めはリリースフェイズの始めに来る。
  'ターンの始め',
  ...PHASES.map(phaseBeginning),
  // 総合ルール 第3部 第10章 3。ターンの終わりはリカバリーフェイズの中に来る。
  'ターンの終わり',
  '登場した時',
  // 総合ルール 第4部 第6章 2-5。
  '移動が起動された時',
  // バトルの中で起こる順（総合ルール 第3部 第12章 1、第14章 1、第16章 1・2-3）。
  // ダメージステップには「～の始め」に誘発する能力が無い（同 第13章・第15章）ので、
  // ステップの並びからは作らず、総合ルールが挙げているものだけを書く。
  'バトルの始め',
  '第１バトルステップの始め',
  '攻撃した時',
  '攻撃された時',
  '第２バトルステップの始め',
  // 総合ルール 第3部 第16章 1-1。負けたユニットはスクエアに残っていないため、
  // 「バトルに負けた時」に誘発する能力は自分では誘発しようがない。誘発させる側が
  // 書けるようになるまで持たない。
  'バトルに勝った時',
  'バトル終了ステップの始め',
  'バトルの終わりに',
  // ルールエフェクトのチェックや効果の解決でも起こり得るため、ターンの順には並ばない。
  // 総合ルール 第4部 第7章 6 の【例】。
  'あなたのユニットがスクエアから捨札に置かれた時',
] as const

export type TriggerEvent = (typeof TRIGGER_EVENTS)[number]

/**
 * 誘発イベントが満たされるたびに自動的に誘発する能力（総合ルール 第4部 第3章 2）。
 *
 * 誘発しても即座には何も起こらず、次にどちらかのプレイヤーが優先権を獲得した時に
 * バンクに入る（同 第4部 第7章 2）。誘発してからバンクに入るまでの間も含め、誘発した
 * 能力そのものは `TriggeredInstance`（`duel.ts`）として盤面が持つ。ここにあるのは
 * カードのテキストが定義している側で、何回誘発しても 1 つである。
 */
export interface TriggeredAbility {
  readonly kind: '誘発型能力'
  readonly event: TriggerEvent
  readonly effect: Effect
}

/**
 * キーワード能力「夢」（総合ルール 第5部 第1章）。
 *
 * 「このカードは、プランゾーンからプレイできる。」という常在型能力であり、プランゾーンに
 * ある時に効果を発揮する（同 1・2）。効果を持たないのは、カードをプレイできるゾーンに
 * 関するルールを変更するだけで、解決される能力ではないためである。
 *
 * 総合ルール 第5部には 23 のキーワード能力があるが、それぞれ能力の種類も働き方も違う。
 * ひとまとめの「キーワード能力」型にせず、実装したものから 1 つずつ型を足していく。
 *
 * キーワード能力の識別子は、日本語名の直訳を名詞で書く（`dream`・`hope`・`trust`・
 * `guts`・`pep`）。能力が何をするかから名前を付けない。ADR-0003 が英語の識別子に
 * 求めているのは総合ルールの語と 1 対 1 に対応していることであって、働きを名前で
 * 説明することではないためである。内容から名前を付けると、どれが直訳でどれが内容ベース
 * かを 23 個ぶん覚える必要が出るうえ、総合ルールの改定で内容が変わった時に名前だけが
 * 取り残される。訳語が一意に定まらない場合もローマ字にはせず、そのキーワードを実装する
 * 時に名詞の直訳から選ぶ。
 */
export interface DreamAbility {
  readonly kind: '常在型能力'
  readonly keyword: '夢'
}

/**
 * キーワード能力「元気」（総合ルール 第5部 第8章）。
 *
 * 「このカードは、第１ダメージステップにダメージを与える」という常在型能力であり
 * （同 2）、バトルでダメージを与えるステップを変更する（同 1）。効果を持たないのは、
 * どのステップでバトルダメージを与えるかを変えるだけで、解決される能力ではないためである
 * （「夢」と同じ形）。
 */
export interface PepAbility {
  readonly kind: '常在型能力'
  readonly keyword: '元気'
}

/**
 * キーワード能力「信頼」（総合ルール 第5部 第4章）。
 *
 * 「相手は、このカードの左右に接するスクエアに自分のユニットを移動することができない」
 * という常在型能力である（同 1・2）。効果を持たないのは、移動先として指定できるスクエアを
 * 狭めるだけで、解決される能力ではないためである（「夢」「元気」と同じ形）。
 *
 * 制限されるのは移動だけで、ユニットのプレイやカードや能力によるゾーン移動は制限されない
 * （同 3）。そのため、これを見るのは移動の経路（`move.ts`）だけになる。
 */
export interface TrustAbility {
  readonly kind: '常在型能力'
  readonly keyword: '信頼'
}

/**
 * キーワード能力「根性」（総合ルール 第5部 第6章）。
 *
 * 「このカードが登場する時、フリーズ状態のかわりにリリース状態でスクエアに置かれる。」という
 * 常在型能力である（同 2）。ユニットがスクエアに置かれる時の状態を置換する（同 1）。効果を
 * 持たないのは、置かれる時の状態を変えるだけで、解決される能力ではないためである
 * （「夢」「元気」「信頼」と同じ形）。
 *
 * 働くのはプレイされてスクエアに置かれる時だけで、カードや能力の効果によってスクエアに
 * 置かれる時には働かない（同 3）。プレイの経路（`play.ts` の `placePlayedUnit`）だけが
 * これを見ることが、その区別にあたる。
 */
export interface GutsAbility {
  readonly kind: '常在型能力'
  readonly keyword: '根性'
}

/**
 * キーワード能力「希望」（総合ルール 第5部 第3章）。
 *
 * 「このカードがスマッシュゾーンに表向きで置かれた時、このカードと同じ色のカードがあなたの
 * エネルギーゾーンにあり、かつこのカードのレベルと同じかそれ以上の枚数のカードがあなたの
 * エネルギーゾーンにあるならば、指定された効果を発揮する」という特別な能力である（同 2）。
 *
 * 誘発型能力に見えるが、種別は起動型・誘発型・常在型のいずれでもない「特別な能力」で
 * あり、バンクを使用せずただちに解決される（同 1）。誘発型能力として持たせるとバンクに
 * 入ってしまうので、別の種類として持つ。
 *
 * ユニットに限らずどの種別のカードも持てる。スマッシュゾーンに置かれるのは山札の 1 番上の
 * カードであって、種別を問わないためである。
 */
export interface HopeAbility {
  readonly kind: '特別な能力'
  readonly keyword: '希望'
  readonly effect: Effect
}

/**
 * テキストによって決められた、カードが行うことまたは行えること
 * （総合ルール 第4部 第1章 1）。
 *
 * 能力には起動型・誘発型・常在型の 3 つがある（同 2）が、起動型はコストを持つ能力を
 * 書けるようになってから足す。常在型は「夢」「元気」「信頼」「根性」だけで、継続効果を
 * 持つものはまだ無い。「希望」はそのどれでもない特別な能力である（同 第5部 第3章 1）。
 */
export type Ability = TriggeredAbility | DreamAbility | PepAbility | TrustAbility | GutsAbility | HopeAbility

/** 誘発型能力を 1 つ書く。 */
export function triggeredAbility(event: TriggerEvent, effect: Effect): TriggeredAbility {
  return { kind: '誘発型能力', event, effect }
}

/** 「夢」。何回書いても同じものなので 1 つを使い回す。 */
export const dream: DreamAbility = { kind: '常在型能力', keyword: '夢' }

/** 「元気」。「夢」と同じく 1 つを使い回す。 */
export const pep: PepAbility = { kind: '常在型能力', keyword: '元気' }

/** 「信頼」。「夢」と同じく 1 つを使い回す。 */
export const trust: TrustAbility = { kind: '常在型能力', keyword: '信頼' }

/** 「根性」。「夢」と同じく 1 つを使い回す。 */
export const guts: GutsAbility = { kind: '常在型能力', keyword: '根性' }

/**
 * キーワード能力「気合」（総合ルール 第5部 第9章）。
 *
 * 「このカードが登場した時、あなたは1000 ダメージを受ける」という誘発型能力である
 * （同 1・2）。ここまでのキーワード能力と違って専用の型を持たないのは、種類も効果も
 * 誘発型能力そのものだからである。「夢」などが専用の型を必要としたのは、効果を持たず、
 * ルールの側が能力の有無を見に行く必要があったためで、「気合」にはその必要が無い。
 *
 * ダメージを受けるのは能力の支配者（「あなた」）であって、相手ではない。
 *
 * この効果によってスマッシュ判定が発生する（同 3）が、それはダメージが 1000 以上に
 * なったことをルールエフェクトが見て始めるもの（同 第4部 第14章 4-12）であり、この能力が
 * 自分で始めるわけではない。
 *
 * 「夢」と同じく、何回書いても同じものなので 1 つを使い回す。
 */
export const spirit: TriggeredAbility = triggeredAbility('登場した時', function* (duel) {
  yield* damagePlayer(duel.controller, 1000)
})

/** 「希望―［効果］」を 1 つ書く。効果はカードごとに違うので受け取る。 */
export function hope(effect: Effect): HopeAbility {
  return { kind: '特別な能力', keyword: '希望', effect }
}
