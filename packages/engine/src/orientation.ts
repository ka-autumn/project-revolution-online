/**
 * カードの向き。リリース状態は縦向き、フリーズ状態は横向きに置くことで示す。
 * バトルスペースのスクエア・トラップゾーン・エネルギーゾーン・スマッシュゾーンに
 * あるカードは、このいずれかの状態を持つ（総合ルール 第2部 第24章 1）。
 *
 * カードに特別な記載がない限り「向き」とはこれを指す（同 1-2）。
 * 表側が見えているかどうかを表す表向き／裏向きは別の概念（同 1-3）。
 */
